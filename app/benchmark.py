"""Measure the three key queries without and with the performance indexes.

What it does:
1. Migrate down to revision 0001 (drops the three performance indexes).
2. ANALYZE, then run EXPLAIN ANALYZE on each query several times.
3. Migrate up to head (recreates the indexes), ANALYZE, and measure again.
4. Write reports/performance_report.md with median timings and the plan used.

The queries are built by the same functions the API uses, so we measure the
real SQL. Each query runs once as a warm-up before timing, so both rounds read
from memory and the comparison is about the plan, not disk caching.

Note: this briefly drops indexes on the database it runs against. Run it on
your local copy, not a shared one.
"""

from __future__ import annotations

import json
import statistics
import time
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, date, datetime
from pathlib import Path
from typing import Any

from alembic import command
from sqlalchemy import Connection, Engine, Select, func, select, text

from app.config import get_settings
from app.db.session import get_engine
from app.services.drugs import DEFAULT_SIMILARITY, ingredient_query, search_query
from app.services.inventory import expiring_query

PAGE = 20


@dataclass(frozen=True)
class BenchQuery:
    key: str
    title: str
    build: Callable[[date], Select[*tuple[Any, ...]]]
    needs_similarity: bool = False


QUERIES = [
    BenchQuery(
        "name_search",
        'Fuzzy name search for "atorvastatn" (typo on purpose)',
        lambda _: search_query("atorvastatn").limit(PAGE),
        needs_similarity=True,
    ),
    BenchQuery(
        "ingredient_lookup",
        'Products with an ingredient starting with "metformin"',
        lambda _: ingredient_query("metformin").limit(PAGE),
    ),
    BenchQuery(
        "expiring_lots",
        "Lots with stock expiring in the next 30 days",
        lambda today: expiring_query(today, 30, include_expired=False).limit(PAGE),
    ),
]


@dataclass
class Measurement:
    median_ms: float
    min_ms: float
    plan: str
    rows: int


def _plan_summary(node: dict[str, Any]) -> list[str]:
    """Scan nodes in the plan, e.g. "Seq Scan on products" or "Bitmap Index Scan (ix_...)"."""
    found: list[str] = []
    node_type = str(node.get("Node Type", ""))
    if "Scan" in node_type:
        target = node.get("Index Name") or node.get("Relation Name") or ""
        found.append(f"{node_type} ({target})" if target else node_type)
    for child in node.get("Plans", []):
        found += _plan_summary(child)
    return found


def measure(conn: Connection, query: BenchQuery, today: date, runs: int) -> Measurement:
    stmt = query.build(today)
    compiled = stmt.compile(dialect=conn.dialect)
    sql = "EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) " + str(compiled)
    timings: list[float] = []
    last: dict[str, Any] = {}
    for attempt in range(runs + 1):  # first run is a warm-up
        if query.needs_similarity:
            conn.execute(
                select(
                    func.set_config(
                        "pg_trgm.word_similarity_threshold", str(DEFAULT_SIMILARITY), True
                    )
                )
            )
        raw = conn.exec_driver_sql(sql, compiled.params).scalar_one()
        last = (json.loads(raw) if isinstance(raw, str) else raw)[0]
        if attempt > 0:
            timings.append(float(last["Execution Time"]))
    seen: list[str] = []
    for step in _plan_summary(last["Plan"]):
        if step not in seen:
            seen.append(step)
    return Measurement(
        median_ms=round(statistics.median(timings), 2),
        min_ms=round(min(timings), 2),
        plan=", ".join(seen),
        rows=int(last["Plan"].get("Actual Rows", 0)),
    )


def measure_all(engine: Engine, today: date, runs: int) -> dict[str, Measurement]:
    with engine.begin() as conn:
        conn.execute(text("ANALYZE"))
    results: dict[str, Measurement] = {}
    with engine.begin() as conn:
        for query in QUERIES:
            results[query.key] = measure(conn, query, today, runs)
    return results


def table_sizes(engine: Engine) -> dict[str, int]:
    with engine.connect() as conn:
        return {
            name: int(conn.execute(text(f"SELECT count(*) FROM {name}")).scalar_one())
            for name in ("products", "active_ingredients", "inventory_lots")
        }


def render(
    before: dict[str, Measurement],
    after: dict[str, Measurement],
    sizes: dict[str, int],
    runs: int,
) -> str:
    lines = [
        "# Performance report",
        "",
        "Generated by `python -m app.cli benchmark`. Do not edit by hand.",
        "",
        f"- Generated: {datetime.now(UTC):%Y-%m-%d %H:%M UTC}",
        f"- Each query: 1 warm-up run, then the median of {runs} runs of EXPLAIN ANALYZE "
        "(PostgreSQL execution time).",
        f"- Table sizes: {sizes['products']:,} products, "
        f"{sizes['active_ingredients']:,} active ingredients, "
        f"{sizes['inventory_lots']:,} inventory lots.",
        "",
        "| Query | Before (no index) | After (with index) | Speedup |",
        "| --- | ---: | ---: | ---: |",
    ]
    for q in QUERIES:
        b, a = before[q.key], after[q.key]
        speedup = b.median_ms / a.median_ms if a.median_ms else float("inf")
        lines.append(f"| {q.title} | {b.median_ms} ms | {a.median_ms} ms | {speedup:.1f}x |")
    lines += ["", "## Query plans", ""]
    for q in QUERIES:
        lines += [
            f"**{q.title}**",
            "",
            f"- Before: {before[q.key].plan}",
            f"- After: {after[q.key].plan}",
            "",
        ]
    return "\n".join(lines)


def run_benchmark(
    runs: int = 7, engine: Engine | None = None, reports_dir: Path | None = None
) -> Path:
    from app.cli import alembic_config

    engine = engine or get_engine()
    config = alembic_config(engine.url.render_as_string(hide_password=False))
    today = date.today()
    sizes = table_sizes(engine)

    started = time.perf_counter()
    print("Dropping performance indexes (migrate down to 0001) ...")
    command.downgrade(config, "0001")
    before = measure_all(engine, today, runs)
    print("Recreating performance indexes (migrate up to head) ...")
    command.upgrade(config, "head")
    after = measure_all(engine, today, runs)

    report = render(before, after, sizes, runs)
    reports_dir = reports_dir or get_settings().reports_dir
    reports_dir.mkdir(parents=True, exist_ok=True)
    path = reports_dir / "performance_report.md"
    path.write_text(report, encoding="utf-8")
    print(report)
    print(f"\nWrote {path} in {time.perf_counter() - started:.1f} s")
    return path
